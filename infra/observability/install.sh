#!/bin/sh
#
# install.sh -- install or re-install the three observability releases that M1 task T1.3 owns:
# Prometheus, kube-state-metrics and Grafana, each from its own chart, each pinned by its own key
# in infra/versions.env, all into the `observability` namespace.
#
# WHY THREE CHARTS INSTEAD OF kube-prometheus-stack
#   infra/versions.env carries three distinct keys -- PROMETHEUS_CHART_VERSION,
#   KUBE_STATE_METRICS_VERSION and GRAFANA_VERSION -- and rule 2 of that file's header makes the
#   key set an M0 interface contract. An umbrella chart yields one pin, and one pin cannot honestly
#   populate three keys: two of them would hold either a duplicate of the umbrella version or the
#   subchart version the umbrella happens to resolve today, and neither is something a reader can
#   install. The umbrella additionally brings the Prometheus Operator and its CRDs, roughly a
#   gigabyte, into a lab cluster sharing a 10 GB WSL2 utility VM with kind, Cilium, eleven Online
#   Boutique services and Locust. Three charts cost three release names and buy three honest pins.
#
# WHAT THIS SCRIPT GUARANTEES
#   Exit 0 means all three releases converged under `helm --wait`, their Services exist, and the
#   Service the Grafana datasource names is the Service the Prometheus release actually created.
#   Any other outcome exits non-zero with the reason named on stderr. There is no partial success:
#   an environment with two of three components up is the kind of half-built state that produces a
#   green `make status` over an instrument that cannot answer a query.
#
# THE PIN CHECK IS THE POINT
#   The script refuses to run if any of the three chart-version keys is absent or empty, and says
#   which. `helm upgrade --install` without --version resolves to whatever the repository's index
#   offers at that moment, so an unpinned install produces a cluster that cannot be rebuilt from
#   the commit that describes it. That directly defeats NFR1 -- the reproducibility claim the whole
#   pinning discipline exists to support -- and it fails silently, since the install still works.
#   All three keys are checked before any of them is used, so one run reports every empty key
#   rather than making the operator discover them one install at a time.
#
#   The keys are read out of infra/versions.env with grep and cut rather than by sourcing the file.
#   Rule 1 of that file's header says it holds values only, with no logic and no substitution, so
#   sourcing would work today; but sourcing executes whatever the file contains, and a check that
#   would execute a malformed line is a worse check than one that reads it. Trailing carriage
#   returns are stripped for the same reason scripts/versions_env_sha256.py normalises them: the
#   file is edited on a Windows host and consumed inside WSL2, and a CRLF would otherwise turn a
#   version into a string with an invisible character in it.
#
# WHAT THIS SCRIPT NEVER DOES
#   It writes nothing to git and reads nothing secret. The Grafana admin password is generated by
#   the chart into a Kubernetes Secret and never appears in this repository; the summary at the end
#   prints the kubectl command that reads it back, not the value.
#
# IDEMPOTENCE
#   Safe to re-run at any time. `helm repo add --force-update` overwrites an existing repository
#   entry instead of failing on it, `helm upgrade --install` installs or upgrades as appropriate,
#   and `--create-namespace` is a no-op once the namespace exists. Re-running does not rotate the
#   Grafana admin password: the chart's password helper looks the existing Secret up first.
#
#   --atomic is deliberately not used. It rolls a failed release back, which destroys the pods and
#   events that explain why it failed; on a lab cluster the useful thing after a failed install is
#   `kubectl describe`, and a rolled-back release has nothing left to describe. A failed release is
#   left in place and the next run of this script upgrades over it.
#
# ORDER
#   Prometheus, then kube-state-metrics, then Grafana. The first two are not ordered relative to
#   each other -- Prometheus discovers KSM through endpointslice service discovery whenever it
#   appears, so installing KSM second costs at most one scrape interval of delay. Grafana is last
#   because its provisioned datasource points at the Prometheus Service, and a Grafana that starts
#   before that Service exists reports a broken datasource on its first health check.
#
# PORTABILITY
#   Strict POSIX sh: no bashisms, no arrays, no [[ ]], no local, no process substitution, no
#   GNU-only flags. It runs under dash in WSL2 Ubuntu, which is where cluster work happens
#   (AGENTS.md, Environment), and under Git Bash on the Windows host. Invoke it as
#   `sh infra/observability/install.sh`, the same way the Makefile invokes everything in scripts/.

set -eu

# Byte-stable grep, cut and helm output regardless of the ambient locale, matching
# scripts/check_hygiene.sh.
LC_ALL=C
export LC_ALL

# Repo root is derived from the script's own location, never hardcoded, so the script works from
# any working directory and from any clone path. Same idiom as scripts/check_hygiene.sh; this file
# sits two levels below the repo root rather than one, so the walk up is ../.. not just ..
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_root=$(CDPATH= cd -- "$script_dir/../.." && pwd)
cd "$repo_root"

versions_file="$repo_root/infra/versions.env"
values_dir="$repo_root/infra/observability"

# The namespace and the three release names are the identifiers everything else in this stack is
# named from. The namespace also appears, spelled out, in the datasource URL in
# grafana-values.yaml; a values file cannot read a shell variable, so that coupling is asserted
# below rather than shared.
NAMESPACE=observability
PROMETHEUS_RELEASE=prometheus
KSM_RELEASE=kube-state-metrics
GRAFANA_RELEASE=grafana

# The prometheus chart names its server Service from the prometheus.server.fullname template: when
# the release name already contains the chart name -- which `prometheus` does -- the result is
# Release.Name + "-" + server.name, and server.name defaults to `server`. Hence prometheus-server.
# That was confirmed by rendering the chart, and it is confirmed again against the live cluster at
# the end of this script, because a name derived from a template is exactly the sort of thing that
# changes quietly across a chart bump.
PROMETHEUS_SERVICE="${PROMETHEUS_RELEASE}-server"

PROMETHEUS_REPO_NAME=prometheus-community
PROMETHEUS_REPO_URL=https://prometheus-community.github.io/helm-charts
# The M1 plan names the `grafana` repository, and that is the one used here. Recorded, because
# it was found while verifying the values keys and should not be lost: the grafana chart in that
# repository is migrating to grafana-community/helm-charts, and its last version there is
# flagged deprecated. grafana-values.yaml carries the finding in full, including the evidence
# that this project's values render identically under the old chart and the new one. Moving
# repository is a technology choice that needs an ADR, so it is flagged there, not made here.
GRAFANA_REPO_NAME=grafana
GRAFANA_REPO_URL=https://grafana.github.io/helm-charts

# Longer than helm's 5m default: on a cold kind node every image in this namespace is pulled over
# the network before anything becomes ready, and a timeout that fires during a first pull reports
# a failure that is really a slow link. This bounds an install, not an experiment.
HELM_TIMEOUT=10m

# Bounded retry for a helm call that reaches a chart repository over the network. Operational
# retry knobs, not protocol quantities (.agents/rules/00-source-of-truth.md) -- literals here
# exactly as HELM_TIMEOUT above is.
HELM_RETRY_ATTEMPTS=3
HELM_RETRY_SLEEP_SECONDS=5

# die takes its reason as one or more words and joins them with spaces, so a long explanation can
# be wrapped across source lines here without wrapping in the output.
die() {
    printf 'observability install: FAIL -- %s\n' "$*" >&2
    exit 1
}

note() {
    printf 'observability install: %s\n' "$*"
}

# Mirrors the OPA-binary fetch loop in guardian/deploy/Dockerfile: a fixed number of attempts,
# break on the first success. A short sleep between attempts is added here because the failures
# this recovers from -- "connection reset by peer", "not a valid chart repository or cannot be
# reached" against prometheus-community.github.io and grafana.github.io -- are transient resets on
# the link, not configuration errors, and they routinely clear within a few seconds. A failed
# attempt's own helm error is left to print straight to stderr.
retry_helm() {
    retry_helm_attempt=1
    while :; do
        if "$@"; then
            return 0
        fi
        if [ "$retry_helm_attempt" -ge "$HELM_RETRY_ATTEMPTS" ]; then
            return 1
        fi
        note "helm command failed (attempt $retry_helm_attempt/$HELM_RETRY_ATTEMPTS); retrying in ${HELM_RETRY_SLEEP_SECONDS}s"
        sleep "$HELM_RETRY_SLEEP_SECONDS"
        retry_helm_attempt=$((retry_helm_attempt + 1))
    done
}

# --- Preflight: tools and files ----------------------------------------------------------------

for tool in helm kubectl; do
    command -v "$tool" >/dev/null 2>&1 \
        || die "$tool is not on PATH. Cluster work runs inside WSL2 (AGENTS.md, Environment);" \
               "run this there, with the tool versions infra/versions.env pins."
done

[ -f "$versions_file" ] || die "no such file: $versions_file"

for values_file in prometheus-values.yaml kube-state-metrics-values.yaml grafana-values.yaml; do
    [ -f "$values_dir/$values_file" ] || die "no such file: $values_dir/$values_file"
done

# The Grafana datasource URL names the Prometheus Service and the namespace as literal text,
# because a Helm values file cannot read a shell variable. This asserts the two agree BEFORE
# anything is installed. Without it, renaming the release here and forgetting the values file
# produces three healthy-looking releases and a Grafana whose only datasource never resolves --
# a failure that shows up in a browser hours later rather than in this script.
grep -q "://${PROMETHEUS_SERVICE}\.${NAMESPACE}\." "$values_dir/grafana-values.yaml" \
    || die "grafana-values.yaml does not name ${PROMETHEUS_SERVICE}.${NAMESPACE} in its" \
           "datasource URL: the release name or namespace set in this script and the URL in" \
           "that file have diverged."

# --- Preflight: every chart version is pinned --------------------------------------------------

# read_pin sets two globals rather than printing, because a function that prints has to be called
# inside a command substitution, and an `exit` inside a command substitution leaves the subshell
# only: the caller would carry on with an empty version string, which is exactly the failure this
# block exists to prevent.
#
# The value is read with grep and cut rather than by sourcing the file. Rule 1 of the
# infra/versions.env header says it holds values only, with no logic and no substitution, so
# sourcing would work today; but sourcing executes whatever the file contains, and a check that
# would execute a malformed line is a worse check than one that reads it. The trailing carriage
# return is stripped for the same reason scripts/versions_env_sha256.py normalises line endings
# before hashing: the file is edited on a Windows host and consumed inside WSL2, and a CRLF would
# otherwise turn a version into a string with an invisible character on the end of it.
pin_present=0
pin_value=''
read_pin() {
    pin_present=0
    pin_value=''
    if grep -q -e "^$1=" "$versions_file"; then
        pin_present=1
        pin_value=$(grep -e "^$1=" "$versions_file" | head -n 1 | cut -d= -f2- | tr -d '\r')
    fi
}

work=$(mktemp -d) || exit 1
trap 'rm -rf "$work"' EXIT HUP INT TERM
pin_problems="$work/pin_problems"
: > "$pin_problems"

# All three keys are checked before any of them is used, so a single run reports every empty key
# rather than making the operator discover them one failed install at a time.
check_pin() {
    read_pin "$1"
    if [ "$pin_present" -eq 0 ]; then
        {
            printf '%s: key absent. infra/versions.env rule 2 keeps every key present even\n' "$1"
            printf '    when empty, so an absent key means that file has been edited against\n'
            printf '    its own contract.\n'
        } >> "$pin_problems"
    elif [ -z "$pin_value" ]; then
        {
            printf '%s: key present but empty. M1 is the milestone that populates the\n' "$1"
            printf '    observability pins; until this holds a chart version there is nothing\n'
            printf '    reproducible to install.\n'
        } >> "$pin_problems"
    fi
}

check_pin PROMETHEUS_CHART_VERSION
check_pin KUBE_STATE_METRICS_VERSION
check_pin GRAFANA_VERSION

if [ -s "$pin_problems" ]; then
    {
        echo "observability install: FAIL -- unpinned chart version(s) in $versions_file:"
        echo
        cat "$pin_problems"
        echo
        echo "An install without --version resolves to whatever the chart repository serves"
        echo "today, which produces a cluster that cannot be rebuilt from the commit that"
        echo "describes it. That is NFR1, so this script refuses rather than installing"
        echo "something unrepeatable."
    } >&2
    exit 1
fi

read_pin PROMETHEUS_CHART_VERSION
prometheus_chart_version="$pin_value"
read_pin KUBE_STATE_METRICS_VERSION
ksm_chart_version="$pin_value"
read_pin GRAFANA_VERSION
grafana_chart_version="$pin_value"

# --- Preflight: the cluster --------------------------------------------------------------------

# Deliberately the last preflight. Everything above inspects this repository and needs no
# cluster, so an operator running this from a machine with nothing up still learns that a chart
# version is unpinned, or that two files have drifted apart, instead of being stopped at the
# first check by a message about the cluster that hides the real defect.
kubectl cluster-info >/dev/null 2>&1 \
    || die "no reachable Kubernetes cluster for the current kubectl context." \
           "Bring the cluster up first."

# Identify the target before touching it, and refuse one this project cannot own.
#
# This script installs into whatever context kubectl currently points at, and on a developer
# machine that is frequently not the cluster the operator has in mind: a stale context from
# another project takes the whole namespace, silently and successfully. That is not hypothetical.
# During M1-T1.3 this very script was run for a syntax check on a host whose kubectl still pointed
# at an unrelated live cluster, and it began installing Prometheus there before it was stopped and
# the release uninstalled. Printing the context, which is what this block did first, would not
# have prevented it -- a name in a log is read after the fact.
#
# So the check refuses. The assertion is on the `kind-` prefix, not on a cluster name, so it is
# not a second, quieter copy of a name T1.1 owns: kubectl writes that prefix for every kind
# cluster whatever it is called. `make up` selects the kind context before calling this script, so
# the guard never fires on the supported path -- only on a by-hand invocation, which is the only
# way the accident can happen. scripts/status.sh already asserts exactly this with no relaxation
# knob, and none is offered here for the same reason: an override is something somebody exports
# once in a shell profile and then never sees again.
current_context=$(kubectl config current-context 2>/dev/null || echo "")
case "$current_context" in
    kind-*) : ;;
    *)
        die "REFUSING -- the current kubectl context is '${current_context:-<none>}', which is not a" \
            "kind cluster (kubectl names those 'kind-<cluster>'). This script creates a namespace and" \
            "three Helm releases in whatever it points at, so it will not act on a context it cannot" \
            "identify as this project's. Select the cluster first, or use 'make up', which does it" \
            "for you."
        ;;
esac
note "target context: $current_context"

# --- Chart repositories ------------------------------------------------------------------------

# --force-update overwrites an existing entry of the same name instead of failing on it, which is
# what makes re-running this script safe on a machine that already has these repositories, or has
# one of them pointing somewhere else.
note "adding and updating chart repositories"
retry_helm helm repo add "$PROMETHEUS_REPO_NAME" "$PROMETHEUS_REPO_URL" --force-update >/dev/null \
    || die "helm repo add $PROMETHEUS_REPO_NAME failed after $HELM_RETRY_ATTEMPTS attempts"
retry_helm helm repo add "$GRAFANA_REPO_NAME" "$GRAFANA_REPO_URL" --force-update >/dev/null \
    || die "helm repo add $GRAFANA_REPO_NAME failed after $HELM_RETRY_ATTEMPTS attempts"
retry_helm helm repo update "$PROMETHEUS_REPO_NAME" "$GRAFANA_REPO_NAME" >/dev/null \
    || die "helm repo update failed after $HELM_RETRY_ATTEMPTS attempts"

# --- Install -----------------------------------------------------------------------------------

# install_chart takes release, chart reference, version and values path. --wait is what turns this
# script's exit status into a statement about readiness rather than a statement about whether the
# API server accepted some YAML.
install_chart() {
    note "$1 <- $2 $3"
    retry_helm helm upgrade --install "$1" "$2" \
        --namespace "$NAMESPACE" \
        --create-namespace \
        --version "$3" \
        --values "$4" \
        --wait \
        --timeout "$HELM_TIMEOUT" \
        || die "helm upgrade --install $1 failed after $HELM_RETRY_ATTEMPTS attempts"
}

install_chart "$PROMETHEUS_RELEASE" "$PROMETHEUS_REPO_NAME/prometheus" \
    "$prometheus_chart_version" "$values_dir/prometheus-values.yaml"

install_chart "$KSM_RELEASE" "$PROMETHEUS_REPO_NAME/kube-state-metrics" \
    "$ksm_chart_version" "$values_dir/kube-state-metrics-values.yaml"

install_chart "$GRAFANA_RELEASE" "$GRAFANA_REPO_NAME/grafana" \
    "$grafana_chart_version" "$values_dir/grafana-values.yaml"

# --- Verify ------------------------------------------------------------------------------------

# --wait already established that every workload became ready. What it did not establish is that
# the Services carry the names the rest of this project assumes, and those names come out of chart
# templates rather than out of anything in this repository. Checking them here turns a chart
# rename into a failed install instead of an empty Grafana panel or a collector reading nothing.
for service in "$PROMETHEUS_SERVICE" "$KSM_RELEASE" "$GRAFANA_RELEASE"; do
    kubectl --namespace "$NAMESPACE" get service "$service" >/dev/null 2>&1 \
        || die "Service $service is absent from namespace $NAMESPACE after a --wait" \
               "install: the chart no longer names its Service what this script expects."
done

# --- Summary -----------------------------------------------------------------------------------

printf '\n'
helm list --namespace "$NAMESPACE"
printf '\n'
printf 'observability install: OK -- 3/3 releases ready in namespace %s\n' "$NAMESPACE"
printf '  prometheus          %s  chart %s\n' "$PROMETHEUS_RELEASE" "$prometheus_chart_version"
printf '  kube-state-metrics  %s  chart %s\n' "$KSM_RELEASE" "$ksm_chart_version"
printf '  grafana             %s  chart %s\n' "$GRAFANA_RELEASE" "$grafana_chart_version"
printf '\n'
printf '  Prometheus, in cluster:  http://%s.%s.svc.cluster.local:80\n' \
    "$PROMETHEUS_SERVICE" "$NAMESPACE"
printf '  Prometheus, from host:   kubectl -n %s port-forward svc/%s 9090:80\n' \
    "$NAMESPACE" "$PROMETHEUS_SERVICE"
printf '  Grafana, from host:      kubectl -n %s port-forward svc/%s 3000:80\n' \
    "$NAMESPACE" "$GRAFANA_RELEASE"
printf '\n'
printf '  Grafana admin user:      admin\n'
printf '  Grafana admin password:  generated by the chart into a Secret. It is never stored in\n'
printf '                           this repository and re-running this script does not rotate\n'
printf '                           it. Read it back with:\n'
printf '    kubectl -n %s get secret %s -o jsonpath="{.data.admin-password}" | base64 -d\n' \
    "$NAMESPACE" "$GRAFANA_RELEASE"
exit 0
