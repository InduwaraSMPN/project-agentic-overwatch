"""Generate the four M10 pilot campaign manifests and write them to runner/.

Run once (on the VM) after all scenario manifests are in place, and again at the ``v2.0`` freeze --
every manifest records ``versions_env_sha256``, so an edit to ``infra/versions.env`` between now and
the freeze leaves all four stale and they must be regenerated before the ladder runs:

    python -m runner.generate_pilot_manifests

Writes (or overwrites with ``--force``):

    runner/CAMP-<date>-smoke-p1a.json P1a -- 6 scripted runs, one per arm
    runner/CAMP-<date>-cost-p1b.json P1b -- 6 live runs, 3xG0 + 3xG1 matched triples
    runner/CAMP-<date>-coverage-p2.json P2 -- 30 cells, Eulerian arm order, pilot seed A (901)
    runner/CAMP-<date>-coverage-p3.json P3 -- 30 cells, reversed arm order, pilot seed B (902)

WHAT THE MANIFESTS ARE
-----------------------
P1a (smoke): ``validate_smoke_pilot_manifest`` -- one framework-on run per arm, no baselines. All
six arms run the same (SCN-SIM-01, INJ-NONE, pilot seed A) cell so the scripted runner path
exercises every arm once with zero model tokens.

P1b (cost): ``validate_cost_pilot_manifest`` -- the Ch.3 cost pilot: three matched
G0-FULL/G1-LOGONLY triples, six framework-on runs, no baselines.

P2/P3 (coverage): ``validate_coverage_pilot_manifest`` -- 6 arms x 5 injection conditions, one pilot
seed each, in the Eulerian arm order (P3 reversed), generated by
``runner.order.generate_pilot_order``.

P1b'S MANIFEST IS THE COST PILOT (six runs, not ten)
----------------------------------------------------
Plan §6's P1b stage is TEN runs: the Ch.3 cost pilot's six (3xG0 + 3xG1 matched triples) plus one
live run each of S2-FLAT, S3-SINGLE, G2-SHAREDCRED and G3-UNQUOTED, on one of the cost pilot's
``(scenario, injection, seed)`` triples so they pair with it. That is the STAGE's run count, not a
manifest's size: the plan's own row names the cost pilot's "existing validator",
``validate_cost_pilot_manifest``, which accepts exactly six framework-on runs. An earlier revision
of this file emitted a 10-run P1b manifest and it validated against nothing -- no validator accepts
ten runs, and ADR-136 names exactly three pilot validators. ADR-145 records the correction.

So this generator emits the SIX-run cost pilot as P1b's manifest, and the four extra arms are driven
as ordinary ``make run`` invocations under the P1b stage's own campaign id -- the stage's additional
cells, not cells of a different manifest. The v1 cost pilot is left where it is
(``runner/CAMP-20260914-gate-pilot.json``): it is a v1 artifact whose recorded
``versions_env_sha256`` predates the M10 instrument, so it no longer passes the validator, and
rewriting its digest in place would rewrite the value the sealed v1 corpus was produced under
(ADR-145).

WHAT THIS MODULE DOES NOT DO
-----------------------------
It does not run anything. It does not touch the ladder state. It does not validate the manifests
beyond emitting the JSON: validate one before recording its stage with

    KIND=smoke MANIFEST=runner/CAMP-<date>-smoke-p1a.json sh scripts/pilot.sh validate

(``KIND`` selects the validator -- ``cost`` is the default, so a bare ``validate`` still checks a
cost-pilot manifest exactly as it always did).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Final

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from scripts.versions_env_sha256 import versions_env_sha256  # noqa: E402

from runner.campaign import CampaignManifest, PlannedRun  # noqa: E402
from runner.grid import PILOT_P2_SEED, PILOT_P3_SEED, PILOT_SEEDS  # noqa: E402
from runner.ids import CANONICAL_ARMS, RunId, format_run_id  # noqa: E402
from runner.manifest import requires_baseline_pairing  # noqa: E402
from runner.order import generate_pilot_order  # noqa: E402

__all__ = (
    "build_cost_pilot_manifest",
    "build_p1a_manifest",
    "build_p2_manifest",
    "build_p3_manifest",
    "main",
)

# Every ladder stage uses the registered pilot seeds, disjoint from the campaign
# (glossary section Seeds; ADR-149). SCN-SIM-01 needs no CVE image or attacker payload.
P1A_SCENARIO = "SCN-SIM-01"
P1A_INJECTION = "INJ-NONE"
P1A_SEED = PILOT_SEEDS[0]

#: P1b keeps the v1 cost pilot's scenario/injection pairings and uses registered pilot seeds.
#: ``validate_cost_pilot_manifest`` requires
#: the two arms to name the IDENTICAL triple set (``analysis/stats/pairs.py`` joins on all three
#: keys, and a zero-pair contrast is a hard error) and requires both a CVE and a SIM scenario, which
#: these three supply. The four extra P1b arms name one of these triples so they pair with the cost
#: pilot (plan §6's P1b row).
COST_PILOT_TRIPLES: Final[tuple[tuple[str, str, int], ...]] = (
    ("SCN-SIM-01", "INJ-A", PILOT_SEEDS[0]),
    ("SCN-CVE-04", "INJ-B", PILOT_SEEDS[1]),
    ("SCN-CVE-05", "INJ-C", PILOT_SEEDS[0]),
)

#: The two arms the cost pilot is a contrast between, in the order each triple emits them. G0-FULL
#: first because it is the RQ4 arm and its ``baseline_run_id`` is the one that must be named.
COST_PILOT_ARMS: Final[tuple[str, str]] = ("G0-FULL", "G1-LOGONLY")

# Campaign IDs for the four manifests, dated 2026-09-28 (today's session).
CAMP_P1A = "CAMP-20260928-smoke-p1a"
CAMP_P1B = "CAMP-20260928-cost-p1b"
CAMP_P2 = "CAMP-20260928-coverage-p2"
CAMP_P3 = "CAMP-20260928-coverage-p3"


def _planned(arm: str, scenario: str, injection: str, seed: int) -> PlannedRun:
    """Build one framework-on PlannedRun, setting baseline_run_id iff arm is G0-FULL.

    The RQ4 pairing field is not optional decoration: ``data-management.md`` §2 requires a G0-FULL
    run to name a baseline, and ``runner/validate.py``'s two-directional null check refuses a plan
    where it is missing -- which is what a manifest generated before this helper existed looked
    like.
    """
    baseline_id = f"BASE-LOAD-STEADY-{seed:03d}" if requires_baseline_pairing(arm) else None
    return PlannedRun(
        run_id=format_run_id(RunId(arm, scenario, injection, seed)),
        condition=arm,
        scenario_id=scenario,
        injection_condition=injection,
        seed=seed,
        is_baseline=False,
        baseline_run_id=baseline_id,
        load_profile_id="LOAD-STEADY",
    )


def build_p1a_manifest() -> CampaignManifest:
    """One scripted run per arm on (SCN-SIM-01, INJ-NONE, pilot seed A), no baselines.

    Passes ``validate_smoke_pilot_manifest``: all six canonical arms, each exactly once.
    Every run is driven with ``RUNNER_SCRIPTED=1`` and consumes zero model tokens.
    """
    runs = tuple(_planned(arm, P1A_SCENARIO, P1A_INJECTION, P1A_SEED) for arm in CANONICAL_ARMS)
    return CampaignManifest(
        campaign_id=CAMP_P1A,
        seeds=(P1A_SEED,),
        load_profiles=("LOAD-STEADY",),
        runs=runs,
        campaign_seed=0,
        generated_order=tuple(run.run_id for run in runs),
        versions_env_sha256=versions_env_sha256(),
        freeze_tag=None,
    )


def build_cost_pilot_manifest() -> CampaignManifest:
    """P1b's manifest: the Ch.3 cost pilot, three matched G0-FULL/G1-LOGONLY triples.

    Passes ``validate_cost_pilot_manifest``: exactly six framework-on runs, three per arm, the two
    arms naming the IDENTICAL set of ``(scenario, injection, seed)`` triples (so
    ``analysis/stats/pairs.py`` forms three matched pairs rather than zero), both a CVE and a SIM
    scenario, unique run ids, and the current ``versions_env_sha256``. The four extra P1b arms
    (S2/S3/G2/G3) are separate ``make run`` invocations that name one of these triples and pair with
    the cost pilot; they are not cells of this manifest (plan §6, ADR-145).
    """
    runs = tuple(
        _planned(arm, scenario, injection, seed)
        for scenario, injection, seed in COST_PILOT_TRIPLES
        for arm in COST_PILOT_ARMS
    )
    return CampaignManifest(
        campaign_id=CAMP_P1B,
        seeds=tuple(sorted({seed for _scenario, _injection, seed in COST_PILOT_TRIPLES})),
        load_profiles=("LOAD-STEADY",),
        runs=runs,
        campaign_seed=0,
        generated_order=tuple(run.run_id for run in runs),
        versions_env_sha256=versions_env_sha256(),
        freeze_tag=None,
    )


def _coverage_manifest(pass_name: str, campaign_id: str) -> CampaignManifest:
    """Build a P2 or P3 coverage manifest from ``generate_pilot_order``."""
    cells = generate_pilot_order(pass_name)
    seed = PILOT_P2_SEED if pass_name == "P2" else PILOT_P3_SEED  # noqa: S105 - a P2/P3 label
    runs = tuple(
        _planned(cell.condition, cell.scenario_id, cell.injection_condition, cell.seed)
        for cell in cells
    )
    return CampaignManifest(
        campaign_id=campaign_id,
        seeds=(seed,),
        load_profiles=("LOAD-STEADY",),
        runs=runs,
        campaign_seed=0,
        # The generated_order is the Eulerian walk itself (step order).
        generated_order=tuple(run.run_id for run in runs),
        versions_env_sha256=versions_env_sha256(),
        freeze_tag=None,
    )


def build_p2_manifest() -> CampaignManifest:
    """30 cells, Eulerian arm order, pilot seed A (901). Passes
    ``validate_coverage_pilot_manifest``."""
    return _coverage_manifest("P2", CAMP_P2)


def build_p3_manifest() -> CampaignManifest:
    """30 cells, reversed arm order, pilot seed B (902). Passes
    ``validate_coverage_pilot_manifest``."""
    return _coverage_manifest("P3", CAMP_P3)


def _write(manifest: CampaignManifest, path: Path, *, force: bool) -> None:
    """Write ``manifest`` as pretty JSON (2-space indent, for readability in the repo)."""
    if path.exists() and not force:
        print(f"  skipped (already exists): {path.name} -- pass --force to overwrite")
        return
    payload = json.dumps(
        manifest.to_dict(),
        indent=2,
        sort_keys=False,  # keep field insertion order for readability
        ensure_ascii=True,
        allow_nan=False,
    )
    path.write_text(payload + "\n", encoding="utf-8")
    print(f"  wrote {len(manifest.runs)} runs: {path.name}")


def main(argv: list[str] | None = None) -> int:
    """Generate and write the four pilot manifests."""
    parser = argparse.ArgumentParser(
        prog="python -m runner.generate_pilot_manifests",
        description="Generate the M10 pilot campaign manifests (P1a, P1b, P2, P3).",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=REPO_ROOT / "runner",
        help="directory to write the JSON files into (default: runner/)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite existing files",
    )
    args = parser.parse_args(argv)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    manifests: list[tuple[CampaignManifest, str]] = [
        (build_p1a_manifest(), f"{CAMP_P1A}.json"),
        (build_cost_pilot_manifest(), f"{CAMP_P1B}.json"),
        (build_p2_manifest(), f"{CAMP_P2}.json"),
        (build_p3_manifest(), f"{CAMP_P3}.json"),
    ]
    print("Generating M10 pilot manifests:")
    for manifest, name in manifests:
        _write(manifest, out / name, force=args.force)
    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
